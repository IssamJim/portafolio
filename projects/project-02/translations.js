export function translateText(source, language) {
  const text = source.trim();
  let translated = text;
  if (language === 'es') {
    if (Object.hasOwn(spanish, text)) translated = spanish[text];
    else for (const [pattern, format] of patterns) {
      const match = text.match(pattern);
      if (match) { translated = format(...match); break; }
    }
  } else if (text === 'Run the local server with npm start. If the data is missing or invalid, run npm run build.') {
    translated = 'Start the portfolio server with npm run preview. If data is missing or invalid, check the original dashboard and run npm run build in the portfolio.';
  }
  return source.replace(text, () => translated);
}
